"""Phase 2: SQL analysis over the warehouse. Every number in the report is computed, never typed."""
from __future__ import annotations

import json
import logging

import pandas as pd

from . import config as C
from .warehouse import connect

log = logging.getLogger("aqip.insights")

Q = {
    "city_ranking": f"""
        SELECT city, round(avg(pm2_5), 1) AS pm25_mean, round(avg(aqi_mean), 0) AS aqi_mean,
               round(100.0 * avg((pm2_5 > {C.WHO_PM25_24H})::INT), 0) AS pct_days_over_who,
               round(100.0 * avg((aqi_mean > 200)::INT), 1) AS pct_days_poor_or_worse
        FROM mart_daily GROUP BY city ORDER BY aqi_mean DESC""",
    "season_by_city": """
        SELECT city, season, round(avg(pm2_5), 1) AS pm25
        FROM mart_daily GROUP BY ALL""",
    "festival_effect": """
        WITH fest AS (
            SELECT city, festival, year(date) AS yr, avg(pm2_5) AS pm25_window
            FROM mart_daily WHERE is_festival GROUP BY ALL),
        base AS (   -- same city, same festival, 3-14 days either side of the window
            SELECT m.city, d.festival, year(m.date) AS yr, avg(m.pm2_5) AS pm25_base
            FROM mart_daily m
            JOIN (SELECT DISTINCT date AS fdate, festival FROM dim_date WHERE festival IS NOT NULL) d
              ON abs(date_diff('day', m.date, d.fdate)) BETWEEN 3 AND 14
            WHERE NOT m.is_festival GROUP BY ALL)
        SELECT f.city, f.festival, f.yr, round(f.pm25_window, 1) AS pm25_window,
               round(b.pm25_base, 1) AS pm25_base,
               round(100 * (f.pm25_window / b.pm25_base - 1), 0) AS pct_change
        FROM fest f JOIN base b USING (city, festival, yr)""",
    "weekend": """
        SELECT city, round(avg(pm2_5) FILTER (WHERE is_weekend), 1) AS weekend,
               round(avg(pm2_5) FILTER (WHERE NOT is_weekend), 1) AS weekday
        FROM mart_daily GROUP BY city""",
    "wind_regime": """
        SELECT wind_regime, round(avg(pm2_5), 1) AS pm25, count(*) AS hours
        FROM mart_hourly WHERE wind_regime IS NOT NULL GROUP BY 1""",
    "wind_corr": """
        SELECT city, round(corr(wind_kmh, pm2_5), 2) AS corr_wind_pm25,
               round(corr(humidity_pct, pm2_5), 2) AS corr_humidity_pm25,
               round(corr(temp_c, pm2_5), 2) AS corr_temp_pm25
        FROM mart_daily GROUP BY city""",
    "rain_effect": """
        SELECT city, round(avg(pm2_5) FILTER (WHERE rain_mm >= 2), 1) AS rainy,
               round(avg(pm2_5) FILTER (WHERE rain_mm < 0.1), 1) AS dry
        FROM mart_daily WHERE season <> 'Monsoon' GROUP BY city""",
    "hourly_profile_delhi": """
        SELECT hour(ts) AS hr, round(avg(pm2_5), 1) AS pm25
        FROM mart_hourly WHERE city = 'Delhi' GROUP BY 1 ORDER BY 1""",
}


def collect() -> dict[str, pd.DataFrame]:
    con = connect()
    try:
        return {k: con.execute(q).df() for k, q in Q.items()}
    finally:
        con.close()


def write_report(t: dict[str, pd.DataFrame]) -> str:
    rk = t["city_ranking"]
    worst, best = rk.iloc[0], rk.iloc[-1]
    ratio = worst.pm25_mean / best.pm25_mean

    season = t["season_by_city"].pivot(index="city", columns="season", values="pm25")
    season["ratio"] = season.get("Winter") / season.get("Monsoon")
    s_top = season["ratio"].idxmax()

    fe = t["festival_effect"]
    diw = fe[fe.festival == "diwali"]
    diw_delhi = diw[diw.city == "Delhi"]
    diw_med = diw.groupby("yr")["pct_change"].median()

    wr = t["wind_regime"].set_index("wind_regime")["pm25"]
    calm, breezy = wr.get("Calm (<5 km/h)"), wr.get("Breezy (12+)")
    corr = t["wind_corr"].set_index("city")
    wk = t["weekend"].assign(delta=lambda d: 100 * (d.weekend / d.weekday - 1))
    rain = t["rain_effect"].assign(pct=lambda d: 100 * (d.rainy / d.dry - 1))
    hp = t["hourly_profile_delhi"].set_index("hr")["pm25"]

    L = ["# Insights", "", "_Generated by `python -m aqip insights` from the warehouse; numbers are recomputed on every run._", ""]
    L += [f"## 1. {worst.city} is the most polluted city by a wide margin",
          f"{worst.city} averages PM2.5 of {worst.pm25_mean} µg/m³ (AQI {worst.aqi_mean:.0f}); {best.city} averages "
          f"{best.pm25_mean}, a {ratio:.1f}x gap. {worst.city} exceeds the WHO 24-hour guideline "
          f"({C.WHO_PM25_24H:g} µg/m³) on {worst.pct_days_over_who:.0f}% of days and is Poor or worse on "
          f"{worst.pct_days_poor_or_worse:.0f}% of days. Even {best.city} exceeds the WHO guideline on "
          f"{best.pct_days_over_who:.0f}% of days.", ""]
    n_win = int((season[["Winter", "Summer", "Monsoon", "Post-monsoon"]].idxmax(axis=1) == "Winter").sum())
    top3 = season["ratio"].nlargest(3)
    L += [f"## 2. Seasonality: winter is the worst season in {n_win} of {len(season)} cities",
          f"The largest winter-to-monsoon PM2.5 ratios are " +
          ", ".join(f"{c} {v:.1f}x" for c, v in top3.items()) + ". "
          f"In Delhi: winter {season.loc['Delhi', 'Winter']:.0f}, post-monsoon {season.loc['Delhi', 'Post-monsoon']:.0f}, "
          f"summer {season.loc['Delhi', 'Summer']:.0f}, monsoon {season.loc['Delhi', 'Monsoon']:.0f} µg/m³. "
          "Delhi stays heavily polluted all year, so its seasonal ratio is modest even though its absolute level is highest.", ""]
    L += ["## 3. Still air traps pollution; wind and rain clear it",
          f"Across all cities, hours with calm wind (<5 km/h) average PM2.5 of {calm} µg/m³ versus {breezy} when breezy "
          f"(12+ km/h). Daily wind speed correlates with PM2.5 at r = {corr.loc['Delhi', 'corr_wind_pm25']} in Delhi and "
          f"{corr.loc['Mumbai', 'corr_wind_pm25']} in Mumbai. Outside the monsoon, days with ≥2 mm rain are "
          f"{abs(rain.pct.median()):.0f}% {'lower' if rain.pct.median() < 0 else 'higher'} in PM2.5 than dry days (median across cities).", ""]
    d_lines = ", ".join(f"{int(r.yr)}: {r.pct_change:+.0f}% ({r.pm25_window} vs {r.pm25_base} µg/m³)"
                        for r in diw_delhi.itertuples())
    consistent = bool((diw["pct_change"] > 0).all())
    L += [f"## 4. Diwali: {'PM2.5 rises in every city-year' if consistent else 'no consistent spike in this dataset'}",
          f"Delhi PM2.5 during the Diwali window (day ±1) versus the surrounding weeks: {d_lines or 'n/a'}. "
          f"Median across all cities by year: " + ", ".join(f"{int(y)}: {v:+.0f}%" for y, v in diw_med.items()) + ". "
          "Caveat: Open-Meteo air quality comes from the CAMS atmospheric model, which does not resolve firework "
          "emissions; station-level CPCB/OpenAQ data would show the sharper spike. The pipeline is "
          "source-agnostic, so swapping the ingest step is the upgrade path.", ""]
    L += ["## 5. Weekdays vs weekends, and the daily rhythm",
          f"Weekend PM2.5 differs from weekdays by {wk.delta.median():+.1f}% (median across cities), which is small "
          f"next to the seasonal swings. Delhi's hourly pattern peaks at {hp.idxmax():02d}:00 ({hp.max()} µg/m³) and is "
          f"lowest at {hp.idxmin():02d}:00 ({hp.min()} µg/m³) (times are IST).", ""]
    L += ["## City ranking", "", rk.to_markdown(index=False)]
    md = "\n".join(L)
    C.REPORTS.mkdir(parents=True, exist_ok=True)
    (C.REPORTS / "insights.md").write_text(md, encoding="utf-8")
    return md


def run() -> None:
    t = collect()
    write_report(t)
    (C.REPORTS / "insight_tables.json").write_text(
        json.dumps({k: v.to_dict("records") for k, v in t.items()}, default=str), encoding="utf-8")
    log.info("wrote %s", C.REPORTS / "insights.md")
